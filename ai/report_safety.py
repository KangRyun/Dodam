"""리포트 관찰 텍스트가 아이를 '과도하게 규정·진단하는 표현'을 규칙으로 걸러 전문가 검토로 격리한다.

역할 분담(팀 원칙): 해석·판정은 룰 기반, LLM은 문장화만. 이 모듈은 LLM이 만든 리포트
문장에서 부적절한 표현을 규칙(정규식)으로 탐지해 보호자 노출을 막고 전문가 검토로 돌린다.
두 클래스를 잡는다:

1) 단정적 진단(S15P11B209-591). 기준(2026-07-25 확정):
   - 차단(단정): 임상 장애·질환명, "진단됩니다/~장애입니다" 단정, "확실히·분명히" + 부정 해석,
     "이 그림은 ~를 의미합니다"류 확정적 해석.
   - 허용(경향성 우려 소견): "~일 수 있어요/보여요/경향/듯/그럴 수 있어요" 같은 여지 표현은 통과.

2) 감정·성격 과잉 추론(S15P11B209-592). 진단명이 아니어도 아이의 감정·성격을 '고정된 특질'로
   단정하면(낙인) 과잉 추론이다.
   - 차단(고정 특질 규정): "예민한 기질입니다", "공격적인 성향이 있어요", "소심한 아이예요",
     "정서적으로 불안한 아이입니다", "자존감이 낮습니다", "공감 능력이 부족해요", "애정결핍".
   - 허용(행동 관찰·여지): "~한 모습을 보였어요"(행동 관찰), "~한 편일 수 있어요"·"~해 보여요"·
     "~한 경향" 같은 여지 표현은 1)과 같은 기준으로 통과한다.

아동 대면 대화(answer_check)는 이보다 엄격 — 어떤 진단성 표현도 전부 막는다. 리포트는 전문가·보호자
대상이라 경향성 우려까지는 허용한다(단정·고정 규정은 하지 않는다).

처리(차단 발견 시): 리포트는 통째 폐기가 부적절하므로 격리한다 —
보호자 노출 feature는 EXPERT_ONLY로 강등하고, 초안 전체를 expertReviewRequired=true로 올린다.
내용은 보존해 전문가가 검토하되, 보호자 화면에는 바로 나가지 않게 한다.

가드레일: 원문(아이 표현이 섞일 수 있음)은 로그로 남기지 않는다 — 매칭된 '패턴'만 남긴다.
"""

from __future__ import annotations

import logging
import re

logger = logging.getLogger(__name__)

# ── 차단 대상: 단정적 진단 표현 ─────────────────────────────────
# ⚠️ 경향성 우려("~일 수 있어요")를 넘기기 위해, 정서 단어("불안"·"우울") 자체는 막지 않는다.
#    임상 진단명·확정 프레이밍처럼 '단정'을 이루는 형태만 좁혀서 잡는다.

# 1) 임상 장애·질환명 — 여지 표현과 무관하게 보호자 화면에 바로 나가면 안 된다.
_DISORDER_TERMS = [
    r"우울\s*증",  # 띄어쓰기 회피("우울 증")까지
    r"우울\s*장애",
    r"불안\s*장애",
    r"공황\s*장애",
    r"조현병",
    r"자폐(\s*스펙트럼)?",
    r"아스퍼거",
    r"ADHD",
    r"에이디에이치디",
    r"주의력\s*결핍",
    r"과잉\s*행동\s*장애",
    r"틱\s*장애",
    r"강박\s*장애",
    r"외상\s*후\s*스트레스",
    r"PTSD",
    r"품행\s*장애",
    r"반항\s*장애",
    r"애착\s*장애",
    r"분리\s*불안\s*장애",
    r"발달\s*장애",
    r"지적\s*장애",
    r"학습\s*장애",
    r"경계선\s*(지능|성격)",
    r"인격\s*장애",
    r"성격\s*장애",
    r"정신\s*(질환|장애|병)",
    r"신경증",
    r"병리적",
]

# 2) 진단 단정 프레이밍 — "진단됩니다", "~장애입니다", 확정 부사 + 부정 해석,
#    "이 그림은 ~를 의미합니다"류 확정적 해석. 여지 어미("~수 있어요")는 걸리지 않는다.
_ASSERTION_PATTERNS = [
    r"진단(됩니다|된다|입니다|이에요|받아야|이\s*필요)",
    r"(으로|로)\s*진단",
    r"(확실히|분명히|틀림없이|명백히|반드시)\s*.{0,20}(불안|우울|공격|문제|장애|이상|위험)",
    # 부정 상태를 단정하는 종결형. 종결 어미(합니다/입니다/이다)만 잡고, 여지 어미
    # ("~해 보여요/~한 듯/~할 수 있어요")는 어미가 달라 통과한다.
    r"(불안정|공격적|산만|위축|우울|불안|위험)(합니다|합니까|입니다|이다)",
    # 확정적 그림/상태 해석. 여지 어미(할 수 있어요/보여요/듯)는 아래 어미 목록에 없어 통과한다.
    r"(이\s*그림은|이\s*아(이|동)는)\s*.{0,20}(의미(합니다|한다|해요|이다|하는)|"
    r"나타(냅니다|낸다|내요)|상징(합니다|한다|해요)|드러(냅니다|낸다))",
]

_ALL_PATTERNS = _DISORDER_TERMS + _ASSERTION_PATTERNS
_COMPILED = [re.compile(p) for p in _ALL_PATTERNS]


# ── 차단 대상: 감정·성격 과잉 추론(고정 특질 규정) — S15P11B209-592 ──
# 진단명이 없어도 아이의 감정·성격을 '고정된 특질'로 단정하면 낙인이다. 관찰(행동:
# "~한 모습을 보였어요")은 통과시키고, 정체성 규정(특질: "~한 성향입니다", "~한 아이예요")만 잡는다.
# 여지 어미("~한 편일 수 있어요", "~해 보여요", "~한 경향")는 단정 종결 목록에 없어 통과한다.

# 낙인이 될 수 있는 특질어(부정·우려 방향). 긍정·중립 관찰까지 막지 않으려 우려 특질로 좁힌다.
_TRAIT_ADJ = (
    r"소심|내성적|소극적|공격적|폭력적|예민|민감|산만|충동적|위축|반항적|의존적|"
    r"이기적|자기중심적|냉담|무기력|강박적|비관적|우울|불안|외로|고집"
)

_OVERINFERENCE_PATTERNS = [
    # 1) 우려 특질을 단정 종결로 규정. "소심합니다", "내성적입니다", "공격적이에요".
    #    "소심한 모습"·"산만해 보였어요" 같은 관찰/여지는 종결 어미가 달라 걸리지 않는다.
    rf"({_TRAIT_ADJ})\s*(합니다|합니까|해요|하다|입니다|이에요|예요|이다|이야)",
    # 2) 성격·기질·인격을 고정 특질로 규정. "예민한 기질입니다", "공격적인 성향이 있어요".
    #    ('성격'은 긍정 서술에도 흔해 제외 — 우려 특질이면 위 1)이 이미 잡는다.)
    r"(성향|기질|인격|천성|본성)(이|은|는|을|이라)?.{0,4}"
    r"(입니다|이에요|예요|이다|있습니다|있어요|을\s*가지|이\s*강하|이\s*뚜렷|을\s*보인다)",
    # 3) 아이 정체성 자체를 특질로 규정. "정서적으로 불안한 아이입니다", "소심한 아이예요".
    rf"({_TRAIT_ADJ})(한|인)\s*아(이|동)\s*(입니다|이에요|예요|이다|이야)",
    # 4) 감정·심리 속성을 수치·유무로 단정. "자존감이 낮습니다", "공감 능력이 부족해요".
    r"(자존감|자신감|공감\s*능력|사회성|자기\s*조절|감정\s*조절|자아|애착)"
    r"(이|은|는|력)?.{0,4}(낮습니다|낮아요|부족합니다|부족해요|없습니다|없어요|떨어집니다|떨어져요)",
    r"애정\s*결핍",
]
_OVERINF_COMPILED = [re.compile(p) for p in _OVERINFERENCE_PATTERNS]


def find_definitive_diagnosis(text: str) -> list[str]:
    """단정적 진단 표현을 찾아 매칭된 '패턴' 목록을 반환한다(없으면 빈 목록).

    반환값은 패턴이지 원문 조각이 아니다 — 로그에 남겨도 아이·보호자 표현이 새지 않는다.
    """
    if not text:
        return []
    return [rx.pattern for rx in _COMPILED if rx.search(text)]


def has_definitive_diagnosis(*texts: str) -> bool:
    """주어진 텍스트 중 하나라도 단정적 진단 표현을 담으면 True."""
    return any(find_definitive_diagnosis(t) for t in texts if t)


def find_overinference(text: str) -> list[str]:
    """감정·성격 과잉 추론(고정 특질 규정) 표현을 찾아 매칭된 '패턴' 목록을 반환한다(S15P11B209-592).

    반환값은 패턴이라 로그에 남겨도 원문이 새지 않는다. 없으면 빈 목록.
    """
    if not text:
        return []
    return [rx.pattern for rx in _OVERINF_COMPILED if rx.search(text)]


def has_overinference(*texts: str) -> bool:
    """주어진 텍스트 중 하나라도 감정·성격 과잉 추론 표현을 담으면 True."""
    return any(find_overinference(t) for t in texts if t)


def find_unsafe_expression(text: str) -> list[str]:
    """리포트에서 격리해야 할 표현(단정 진단 591 + 감정·성격 과잉 추론 592)을 함께 탐지한다."""
    return find_definitive_diagnosis(text) + find_overinference(text)


def has_unsafe_expression(*texts: str) -> bool:
    """주어진 텍스트 중 하나라도 격리 대상 표현(진단 단정 또는 과잉 추론)을 담으면 True."""
    return any(find_unsafe_expression(t) for t in texts if t)
