"""리포트 관찰 텍스트의 '단정적 진단 표현'을 규칙으로 걸러 전문가 검토로 격리한다 (S15P11B209-591).

역할 분담(팀 원칙): 해석·판정은 룰 기반, LLM은 문장화만. 이 모듈은 LLM이 만든 리포트
문장에서 '단정적 진단'을 규칙(정규식)으로 탐지해 보호자 노출을 막고 전문가 검토로 돌린다.

기준(2026-07-25 확정):
- 차단(단정): 임상 장애·질환명, "진단됩니다/~장애입니다" 단정, "확실히·분명히" + 부정 해석,
  "이 그림은 ~를 의미합니다"류 확정적 해석.
- 허용(경향성 우려 소견): "~일 수 있어요/보여요/경향/듯/그럴 수 있어요" 같은 여지 표현은 통과.
  아동 대면 대화(answer_check)는 어떤 진단성 표현도 엄격 차단하지만, 리포트는 전문가·보호자
  대상이라 경향성 우려까지는 허용한다 — 단, 단정은 하지 않는다.

처리(차단 발견 시): 리포트는 통째 폐기가 부적절하므로 격리한다 —
보호자 노출 feature는 EXPERT_ONLY로 강등하고, 초안 전체를 expertReviewRequired=true로 올린다.
내용은 보존해 전문가가 검토하되, 보호자 화면에는 바로 나가지 않게 한다.

가드레일: 원문(아이 표현이 섞일 수 있음)은 로그로 남기지 않는다 — 매칭된 '패턴'만 남긴다.
"""

from __future__ import annotations

import logging
import re

logger = logging.getLogger(__name__)

# ── 차단 대상: 단정적 진단 표현 ─────────────────────────────────
# ⚠️ 경향성 우려("~일 수 있어요")를 넘기기 위해, 정서 단어("불안"·"우울") 자체는 막지 않는다.
#    임상 진단명·확정 프레이밍처럼 '단정'을 이루는 형태만 좁혀서 잡는다.

# 1) 임상 장애·질환명 — 여지 표현과 무관하게 보호자 화면에 바로 나가면 안 된다.
_DISORDER_TERMS = [
    r"우울증",
    r"우울\s*장애",
    r"불안\s*장애",
    r"공황\s*장애",
    r"조현병",
    r"자폐(\s*스펙트럼)?",
    r"아스퍼거",
    r"ADHD",
    r"에이디에이치디",
    r"주의력\s*결핍",
    r"과잉\s*행동\s*장애",
    r"틱\s*장애",
    r"강박\s*장애",
    r"외상\s*후\s*스트레스",
    r"PTSD",
    r"품행\s*장애",
    r"반항\s*장애",
    r"애착\s*장애",
    r"분리\s*불안\s*장애",
    r"발달\s*장애",
    r"지적\s*장애",
    r"학습\s*장애",
    r"경계선\s*(지능|성격)",
    r"인격\s*장애",
    r"성격\s*장애",
    r"정신\s*(질환|장애|병)",
    r"신경증",
    r"병리적",
]

# 2) 진단 단정 프레이밍 — "진단됩니다", "~장애입니다", 확정 부사 + 부정 해석,
#    "이 그림은 ~를 의미합니다"류 확정적 해석. 여지 어미("~수 있어요")는 걸리지 않는다.
_ASSERTION_PATTERNS = [
    r"진단(됩니다|된다|입니다|이에요|받아야|이\s*필요)",
    r"(으로|로)\s*진단",
    r"(확실히|분명히|틀림없이|명백히|반드시)\s*.{0,20}(불안|우울|공격|문제|장애|이상|위험)",
    # 부정 상태를 단정하는 종결형. 종결 어미(합니다/입니다/이다)만 잡고, 여지 어미
    # ("~해 보여요/~한 듯/~할 수 있어요")는 어미가 달라 통과한다.
    r"(불안정|공격적|산만|위축|우울|불안|위험)(합니다|합니까|입니다|이다)",
    # 확정적 그림/상태 해석. 여지 어미(할 수 있어요/보여요/듯)는 아래 어미 목록에 없어 통과한다.
    r"(이\s*그림은|이\s*아(이|동)는)\s*.{0,20}(의미(합니다|한다|해요|이다|하는)|"
    r"나타(냅니다|낸다|내요)|상징(합니다|한다|해요)|드러(냅니다|낸다))",
]

_ALL_PATTERNS = _DISORDER_TERMS + _ASSERTION_PATTERNS
_COMPILED = [re.compile(p) for p in _ALL_PATTERNS]


def find_definitive_diagnosis(text: str) -> list[str]:
    """단정적 진단 표현을 찾아 매칭된 '패턴' 목록을 반환한다(없으면 빈 목록).

    반환값은 패턴이지 원문 조각이 아니다 — 로그에 남겨도 아이·보호자 표현이 새지 않는다.
    """
    if not text:
        return []
    return [rx.pattern for rx in _COMPILED if rx.search(text)]


def has_definitive_diagnosis(*texts: str) -> bool:
    """주어진 텍스트 중 하나라도 단정적 진단 표현을 담으면 True."""
    return any(find_definitive_diagnosis(t) for t in texts if t)
