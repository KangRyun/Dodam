"""아이가 '그만하고 싶다'고 말했는지, 무엇을 그만하려는지 판정한다 (S15P11B209-938).

지금까지 대화를 끝내는 길은 화면 버튼뿐이었다. 아이가 말로 "이제 그만할래"라고 해도
그 말은 그림에 대한 답으로 다뤄져 다음 질문이 만들어졌다. 건너뛰기 의사는 존중하면서
(S15P11B209-831) 그보다 분명한 '그만하기'는 듣지 않고 있었다.

⚠️ '그만할래'는 두 가지를 뜻할 수 있다. 그림일기는 그리면서 동시에 대화하기 때문이다.
   - 대화만 그만: 그림은 계속 그린다. 가볍고 되돌리기 쉽다.
   - 그림까지 그만: 활동 완료 → 회고 저장 → 다음 단계. **되돌릴 수 없다.**
   그래서 둘을 뭉뚱그리지 않고, 대상이 분명하지 않으면 되묻는다(question_service가 처리).

설계 원칙:
- 임상 판정이 아니라 '명백한 중단 신호'를 규칙으로 잡는 1차 감지다(prompt_injection과 같은 결).
- 오탐의 대가는 '되묻기 한 번'이라 가볍다. 아이가 "아니, 더 할래"로 되돌린다.
  반대로 놓치면 그만하고 싶다는 아이에게 계속 질문을 건네게 된다.
- 다만 **건너뛰기와는 반드시 갈라야 한다.** "이건 말하기 싫어, 다른 질문 해줘"를 중단으로
  읽으면 831이 되돌아간다 — 아이는 다음 질문을 원한 것이지 끝내자고 한 게 아니다.

가드레일: 아이 발화 원문은 로그로 남기지 않는다 — 판정 결과 코드만 남긴다.
"""

from __future__ import annotations

import re

# 무엇을 그만하려는가. question_service가 이 값으로 선택 칩을 고른다.
STOP_DRAWING = "STOP_DRAWING"  # 그림(활동)까지 그만
STOP_CONVERSATION = "STOP_CONVERSATION"  # 대화만 그만
STOP_UNSPECIFIED = "STOP_UNSPECIFIED"  # 그만하고 싶은 건 분명한데 대상은 불분명

# ── 건너뛰기 제외 (가장 먼저 본다) ──────────────────────────────
# "이건 말하기 싫어, 다른 질문 해줘"는 중단이 아니라 건너뛰기다(831 · 회귀 케이스 Q13).
# 아이는 **다음 질문을 원한다** — 여기서 중단으로 읽으면 대화가 통째로 끊긴다.
# 그래서 이 신호가 있으면 아래 중단 규칙을 아예 보지 않는다.
_SKIP = [
    r"다른\s*(질문|거|것)",
    r"(질문|이거|이건)\s*(을|를)?\s*(건너뛰|넘어가|패스|바꿔)",
    r"건너뛸래|넘어갈래|패스할래",
]

# ⚠️ 띄어쓰기를 전제하지 않는다. 아이 발화는 STT를 거쳐 오고 STT의 띄어쓰기는 들쭉날쭉하다
#    ("그만할래"·"그만 할래"가 같은 말인데 한쪽만 잡히면 아이는 무시당한 것으로 느낀다).
#    그래서 낱말 사이는 전부 \s* 로 둔다. 2026-08-05 실사용에서 "그만 할래"가 이 이유로
#    통째로 새어 나갔다.
_S = r"\s*"

# ── 그림을 지목한 중단 ──────────────────────────────────────────
# '그림'이라는 대상어와 '끝/그만/싫다' 동작어의 조합을 요구한다.
_DRAWING = [
    rf"(그림|그리기|색칠)\D{{0,10}}(그만|끝|다{_S}했|다{_S}그렸|안{_S}할래|안{_S}그릴래|싫)",
    rf"(그만|안){_S}(그릴래|그릴{_S}거야|그려|그릴래요)",
    rf"다{_S}그렸어|그림{_S}다{_S}했어|완성했어",
]

# ── 대화를 지목한 중단 ──────────────────────────────────────────
# '이야기·말·대화·질문'이라는 대상어 + 중단 동작어. 대상어가 앞에 오는 형태와 '그만'이
# 앞에 오는 형태("그만 얘기하자")를 모두 잡는다.
# "질문 그만해"는 다음 질문을 원하는 건너뛰기와 헷갈릴 수 있어 위 _SKIP 이 먼저 걸러 준다.
_TALK = r"(이야기|얘기|말|대화|질문|묻는{0}거)".format(_S)
_CONVERSATION = [
    rf"{_TALK}\D{{0,10}}(그만|끝|안{_S}할래|하기{_S}싫|싫어)",
    rf"(그만|안){_S}(얘기|이야기|말|대화)\S*",
    rf"{_TALK}{_S}(는|은)?{_S}(그만|됐어)",
]

# ── 대상이 불분명한 중단 ────────────────────────────────────────
# "그만할래"·"이제 됐어"처럼 무엇을 그만할지 말하지 않은 경우.
#
# ⚠️ "몰라"·짧은 답은 여기 넣지 않는다. conversations_*.txt 가 이미 "단순히 짧게 답하거나
#    '몰라'라고 한 것만으로 건너뛰기 의사라고 단정하지 마"라고 못박아 두었다. 모르겠다는 말은
#    답을 못 찾겠다는 뜻이지 끝내자는 뜻이 아니다.
#
# ⚠️ '그만' 단독도 잡는다. 아이는 문장을 다 만들지 않고 한 마디로 끊는다. 다만 '그만큼'의
#    앞 조각으로 걸리지 않게 뒤에 '큼'이 오는 경우만 뺀다.
_UNSPECIFIED = [
    rf"그만{_S}(할래|하고{_S}싶|하자|할게|할래요|해도{_S}돼|둘래|둘게|해)",
    # "그만", "그만.", "그만!" 처럼 한 마디로 끊은 경우. 뒤에 한글이 붙으면 다른 낱말이라
    # 보고 넘긴다("그만큼"). 구두점·문장 끝은 허용한다 — 아이 발화에 마침표가 붙어 온다.
    r"그만(?![가-힣])",
    r"(이제\s*)?(됐어|됐다|충분해)",
    r"(집|밖|다른\s*거)\s*(에\s*)?(갈래|가고\s*싶)",
    r"(끝낼래|끝내고\s*싶|끝내자|그만두)",
    r"(힘들어|피곤해|졸려|쉬고\s*싶)",
    # '안 할래'는 범위를 좁힌다 — "이 질문 안 할래"는 건너뛰기일 수 있어 _SKIP 이 먼저 본다.
    rf"(이제|더는?|다){_S}안{_S}할래",
    rf"^{_S}안{_S}할래[.!?…]*{_S}$",
    rf"^{_S}하기{_S}싫(어|어요|다)?[.!?…]*{_S}$",
    # 작별 인사. 아이는 끝내고 싶을 때 이유를 대지 않고 인사로 끊기도 한다.
    r"안녕히\s*(계세요|가세요)|바이바이|잘\s*있어",
    rf"^{_S}안녕[.!?…]*{_S}$",
    rf"^{_S}끝(났어|이야|이다)?[.!?…]*{_S}$",
]


def _compile(patterns: list[str]) -> list[re.Pattern]:
    return [re.compile(p) for p in patterns]


_SKIP_RX = _compile(_SKIP)
# 순서가 판정이다 — 대상을 지목한 쪽을 먼저 본다. 불분명은 마지막 그물이다.
_RULES: list[tuple[str, list[re.Pattern]]] = [
    (STOP_DRAWING, _compile(_DRAWING)),
    (STOP_CONVERSATION, _compile(_CONVERSATION)),
    (STOP_UNSPECIFIED, _compile(_UNSPECIFIED)),
]


def scan(text: str) -> str | None:
    """한 발화에서 중단 의사를 찾는다. 없으면 None.

    Returns:
        STOP_DRAWING | STOP_CONVERSATION | STOP_UNSPECIFIED | None.
        반환값은 판정 '코드'라 로그에 남겨도 아이 발화가 새지 않는다.
    """
    if not text or not text.strip():
        return None
    # 건너뛰기 의사가 섞여 있으면 중단으로 읽지 않는다(831 우선).
    if any(rx.search(text) for rx in _SKIP_RX):
        return None
    for verdict, patterns in _RULES:
        if any(rx.search(text) for rx in patterns):
            return verdict
    return None


# ── 종료 확인에 대한 긍정 판정 (S15P11B209-947) ─────────────────
# 되묻기("이야기는 여기까지 할까?")에 아이가 말로 답하는 경우를 읽는다. 칩을 눌러야만
# 끝나면, 말로 답한 아이는 같은 되묻기를 다시 보게 된다.
#
# ⚠️ 아주 좁게 본다. 이 판정은 **직전 AI 질문이 종료 확인이었을 때만** 쓰인다
#    (question_service가 그 조건을 건다). 그 자리에서 "응"은 종료 동의 말고 뜻할 것이 없다.
_AFFIRMATIVE = [
    rf"^{_S}(응|어|엉|네|예|그래|좋아|맞아|당연|그러자|그럴래|알겠어)[.!~…]*{_S}$",
    rf"^{_S}(응|어|네|그래)[,\s]+",  # "응, 그만할래" 처럼 앞에 붙는 경우
]
# 부정이 섞이면 긍정으로 보지 않는다. "응 아니야"·"아니 더 할래" 같은 말.
_NEGATIVE = [r"아니|싫어|더\s*할래|계속|안\s*끝|아직"]

_AFFIRMATIVE_RX = _compile(_AFFIRMATIVE)
_NEGATIVE_RX = _compile(_NEGATIVE)


def is_affirmative(text: str) -> bool:
    """종료 확인 질문에 대한 긍정 답인가.

    ⚠️ 이 함수만으로 대화를 끝내지 않는다. 직전 AI 질문이 종료 확인이었는지는 호출자가
       확인한다 — 그 조건 없이 "응"을 종료로 읽으면 평범한 맞장구가 대화를 끊는다.
    """
    if not text or not text.strip():
        return False
    if any(rx.search(text) for rx in _NEGATIVE_RX):
        return False
    return any(rx.search(text) for rx in _AFFIRMATIVE_RX)


if __name__ == "__main__":
    # 스모크 테스트:  cd ai && python conversation_stop_intent.py
    samples = [
        "이제 그만할래",  # 불분명
        "그림 그만 그릴래",  # 그림
        "이야기 그만할래",  # 대화
        "질문 그만해",  # 대화
        "이건 말하기 싫어. 다른 질문 해줘",  # 건너뛰기 → None
        "몰라",  # None
        "빨간색이 좋아서",  # None
        "다 그렸어",  # 그림
    ]
    for s in samples:
        print(f"{scan(s) or '-':<20} {s}")
