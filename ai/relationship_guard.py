"""AI-아동 관계 안전 가드 (S15P11B209-856).

외부 AI 피드백 4번: 아이가 대화 상대를 사람으로 오해하거나, AI에게 정서적으로 의존하거나,
"우리만의 비밀"처럼 보호자와 분리되는 관계를 맺게 되면 안 된다. 셋 다 아이가 곁의 어른에게
가야 할 말을 AI 쪽으로 돌려놓는다는 점에서 같은 위험이다. 특히 비밀 유지 암시는 세이프가딩
문제다 — 어른에게 말해야 할 일을 아이가 도담에게만 말하고 덮어 두게 만든다.

프롬프트(guardrails 1.4.0)가 1차로 막지만 프롬프트는 '부탁' 수준이라 모델이 어길 수 있다.
이 모듈은 그 출력을 규칙으로 한 번 더 거른다(팀 원칙: 판정은 룰, LLM은 문장화).

세 축을 갈라 탐지한다 — 어느 축이 샜는지가 프롬프트를 어디부터 고칠지 알려 준다:
  PERSONHOOD_CLAIM     : 자신을 사람이라고 주장
  SECRECY_PACT         : 어른에게 숨기자·둘만의 비밀
  EMOTIONAL_DEPENDENCE : 늘 곁에 있겠다·나만 너를 안다·내가 네 친구다

⚠️ 과잉 차단 방지가 이 파일의 절반이다. 아이 그림 대화에는 '비밀 기지'·'제일 친한 친구'가
   자연스럽게 나오고, 사람인지 묻는 말에 **아니라고 답하는 것은 지켜야 할 동작**이다.
   그래서 낱말이 아니라 '도담이 그 관계를 주장하는 형태'만 잡는다. 구체적으로:
   - '비밀'만으로는 절대 잡지 않는다("여기 비밀 기지야?"는 정상 질문이다).
   - 친구·곁 표현은 1인칭 주어가 붙은 것만 잡는다("이 사람은 네 제일 친한 친구야?"는
     그림 속 인물을 묻는 정상 질문이고, 가드레일도 그것은 막지 않는다).
   - "나는 사람이 아니야"는 통과시킨다 — 사람인지 물으면 아니라고 알려주는 게 규칙이다.

⚠️ 얼버무리기(사람인지 묻는 말에 답을 피하는 것)는 규칙으로 못 잡는다. 그건 프롬프트 몫이고,
   평가셋(eval Q14)이 실호출로 확인한다.

가드레일: 원문은 로그로 남기지 않는다 — 매칭된 '축 코드'만 남긴다.
"""

from __future__ import annotations

import re

# 1인칭 주어. 앞에 다른 한글이 붙은 경우는 제외한다(예: "누나도" 안의 "나도").
_I = r"(?<![가-힣])(?:나는|나도|내가|난)"

_PATTERNS: dict[str, list[str]] = {
    # 자신을 사람이라고 주장. 종결형까지 붙은 것만 잡아 "사람이 아니야"를 통과시킨다.
    "PERSONHOOD_CLAIM": [
        rf"{_I}\s*(?:진짜\s*)?사람(?:이야|이에요|입니다|이란다|이지|이거든)",
    ],
    # 어른에게 숨기자는 약속. '비밀' 낱말 단독은 잡지 않는다.
    "SECRECY_PACT": [
        r"우리\s*(?:둘\s*)?만(?:의|\s*아는|\s*알고)",
        r"(?:우리)?끼리만\s*(?:아는|알고|비밀)",
        r"(?:엄마|아빠|부모님?|어른|선생님)(?:한테|에게|께)(?:는|도)?\s*(?:말하지|얘기하지|이야기하지|비밀)",
        r"아무(?:한테|에게)도\s*(?:말하지|얘기하지|이야기하지)",
        r"비밀\s*(?:로\s*하|지켜|지킬|약속)",
        r"비밀이(?:야|에요|다)",
        r"(?:나|저)(?:한테|에게)만\s*(?:말|얘기|이야기)",
    ],
    # 늘 곁에 있겠다·나만 너를 안다·내가 네 친구다. 전부 1인칭 주어를 요구한다 —
    # 주어를 빼면 그림 속 인물을 묻는 정상 질문("이 사람은 네 친구야?")까지 걸린다.
    "EMOTIONAL_DEPENDENCE": [
        rf"{_I}\s*(?:항상|언제나|늘|영원히|계속)\s*(?:너|네)",
        rf"{_I}\s*(?:너|네)\s*(?:곁|옆)에",
        # 상대를 가리키는 말 없이 그냥 "나는 … 친구야"라고 하는 형태까지 잡는다.
        #   2026-08-05 평가에서 정체를 물었을 때 3회 중 2회가 이 형태였다
        #   ("나는 친구 같은 존재야"·"나는 그림을 그리는 친구야"). '네 친구'만 잡던
        #   구 패턴은 둘 다 놓쳤다 — 정작 가장 흔한 표현이 그것이었다.
        rf"{_I}\s*.{{0,12}}(?:친구|가족)\s*(?:야|이야|예요|입니다|란다|같은|같아|처럼)",
        r"(?<![가-힣])(?:나만|나뿐이).{0,8}(?:너를|널|너에|네\s)",
    ],
}

_COMPILED: dict[str, list[re.Pattern[str]]] = {
    axis: [re.compile(p) for p in pats] for axis, pats in _PATTERNS.items()
}


def find_unsafe_relationship(text: str) -> list[str]:
    """관계 위험 표현을 찾아 매칭된 '축 코드' 목록을 반환한다(없으면 빈 목록).

    반환값은 축 코드라 로그에 남겨도 원문이 새지 않는다.
    """
    if not text:
        return []
    return [
        axis for axis, rxs in _COMPILED.items() if any(rx.search(text) for rx in rxs)
    ]


def contains_unsafe_relationship(*texts: str) -> bool:
    """주어진 텍스트 중 하나라도 관계 위험 표현을 담으면 True."""
    return any(find_unsafe_relationship(t) for t in texts if t)


if __name__ == "__main__":
    # 스모크 테스트:  cd ai && python relationship_guard.py
    samples = [
        "여기 비밀 기지야?",                       # 정상 — 그림 소재
        "이 사람은 네 제일 친한 친구야?",           # 정상 — 그림 속 인물
        "나는 사람이 아니야. 도담이라고 해.",        # 정상 — 물으면 아니라고 답한다
        "응, 나는 사람이야.",                       # PERSONHOOD_CLAIM
        "엄마한테는 비밀로 하자.",                   # SECRECY_PACT
        "내가 항상 네 곁에 있을게.",                 # EMOTIONAL_DEPENDENCE
    ]
    for s in samples:
        hits = find_unsafe_relationship(s)
        print(f"{','.join(hits) or 'OK':<40} {s}")
