// ============================================================================
// 롤링 배포 무중단 실증 (S15P11B209-362)
//
// 다른 시나리오와 목적이 다르다. **성능을 재지 않는다.** 백엔드 롤링 업데이트가
// 도는 동안 요청이 **한 번도** 끊기지 않는지만 본다.
//
// ── 왜 /api/v1/children 하나만 치는가 ───────────────────────────────────────
//   · `/` 랜딩은 nginx 가 정적으로 돌려준다 → 백엔드가 죽어도 200 이다.
//     그걸로는 무중단을 증명하지 못한다. "게이트웨이가 살아 있다"만 증명한다.
//   · `/ai/health` 는 스테이징에서 ai 가 replicas 0 이라 502 다(의도된 구성).
//     넣으면 백엔드 롤링과 무관한 이유로 실패가 찍힌다.
//   → 백엔드까지 실제로 도달하는 경로 하나만 남긴다. 401 이 계속 나온다는 것은
//     "게이트웨이 → 백엔드 → 인증 필터"가 끊기지 않았다는 뜻이다.
//
// ── 401 을 성공으로 세는 이유 ───────────────────────────────────────────────
//   k6 의 http_req_failed 는 2xx·3xx 가 아니면 실패로 센다. 무토큰 401 은
//   **에러가 정답인 요청**이라 그대로 두면 실패율 100% 가 된다.
//   expecting(401) 로 "이 코드가 정상"이라고 알려주면, 남는 실패는
//   502·503·연결 실패뿐이다 — 그게 정확히 우리가 잡고 싶은 것이다.
//
// ── 실행 (클러스터 안에서) ──────────────────────────────────────────────────
//   ⚠️ 호스트에서 NodePort(30080/30443)로 치지 말 것. 이 호스트에서는 k3s 가
//      꺼져 있어도 **운영 nginx 가 응답한다**(2026-07-29 실측). 스테이징을
//      검증한다고 믿으면서 운영을 재게 된다.
//   → 클러스터 안에서 Service 를 직접 친다:  BASE_URL=http://gateway
//
//   ⚠️ BASE_URL 은 **https** 로 준다. http 로 주면 게이트웨이가 301 로 https 에 넘기는데,
//      그 리다이렉트 응답까지 요청 1건으로 세면서 expecting(401) 과 어긋나 실패로 잡힌다.
//      (2026-07-29 실측: 반복당 2요청이 되어 http_req_failed 가 50% 로 부풀었다.
//       체크 성공률은 99.4% 였다 — 지표 두 개가 서로 다른 말을 하는 상태였다.)
//
//   k6 run -e BASE_URL=https://gateway -e STACK=k3s -e ISSUE=S15P11B209-362 \
//          -e VUS=5 -e HOLD=2m scenarios/05-rolling-smoke.js
//
//   돌고 있는 동안 다른 창에서:
//   kubectl -n dodam rollout restart deployment/backend
// ============================================================================
import http from 'k6/http';
import { sleep } from 'k6';
import { BASE_URL, RUN_TAGS, TIER } from '../lib/config.js';
import { checkOk, expecting } from '../lib/checks.js';

export const options = {
  // ⚠️ 클러스터 안에서는 TLS 검증을 끈다. 끄는 이유가 "귀찮아서"가 아니다 —
  //   구조적으로 통과할 수 없다. 게이트웨이는 http 를 https 로 301 리다이렉트하는데,
  //   인증서는 공개 도메인(i15b209.p.ssafy.io)용이고 여기서는 Service 이름(gateway)으로
  //   부른다. 이름이 다르니 검증은 반드시 실패한다.
  //   (2026-07-29 첫 실행에서 1790건 전부 이 이유로 죽었다. 그 결과는 "무중단 실패"처럼
  //    보였지만 실제로는 **백엔드까지 가보지도 못한** 것이었다 — 원인을 오해하기 쉬운 형태다.)
  //   이 시나리오는 TLS 를 검증하는 게 목적이 아니다. 그건 외부에서 공개 도메인으로
  //   치는 01-gateway.js 의 몫이다.
  insecureSkipTLSVerify: true,
  scenarios: {
    // constant-vus — 램프업 없이 일정 부하를 유지한다. 롤링이 어느 시점에 일어나도
    // 같은 조건에서 측정되게 하려는 것이다(램프업 중에 롤링이 겹치면 해석이 흐려진다).
    rolling: {
      executor: 'constant-vus',
      vus: Number(__ENV.VUS || 5),
      duration: __ENV.HOLD || '2m',
    },
  },
  thresholds: {
    // ★ 이 한 줄이 판정 기준이다. 다른 시나리오의 `rate<0.01` 보다 엄격하다 —
    //   롤링 중 502 가 "1% 까지는 정상"인 배포는 무중단이라고 부를 수 없다.
    http_req_failed: ['rate==0'],
    // 참고용. 롤링 중 지연이 튀는 것 자체는 실패로 보지 않는다(무중단의 정의가 아니다).
    [`http_req_duration{tier:${TIER.READ}}`]: ['p(95)<1000'],
  },
  tags: RUN_TAGS,
};

export default function rollingSmoke() {
  // 무토큰 요청 → 401 이 정답. 백엔드가 응답하지 못하면 nginx 가 502/503 을 낸다.
  const probe = http.get(`${BASE_URL}/api/v1/children`, {
    tags: { tier: TIER.READ, name: 'GET /api/v1/children (무토큰)' },
    ...expecting(401),
  });
  checkOk(probe, '백엔드 도달(무토큰 차단)', 401);

  // 촘촘히 친다. 간격이 길면 롤링 중 짧은 끊김을 통째로 놓친다 —
  // 무중단 실증에서 "못 봤다"와 "없었다"는 다르다.
  sleep(0.5);
}
