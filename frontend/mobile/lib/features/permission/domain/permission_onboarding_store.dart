/// 로그인 직후 한 번만 세우는 권한 안내의 "이미 물어봤다" 표시를 보관한다.
///
/// 기기 권한은 계정이 아니라 **앱 설치 단위**로 부여된다 — 같은 기기를 두 보호자가
/// 나눠 써도 이미 허용·거부된 상태는 그대로다. 계정별로 기록하면 두 번째 보호자에게
/// 아무 일도 일어나지 않는 화면(시스템이 다시 묻지 않는다)을 한 번 더 보여주게
/// 되므로, 이 표시도 기기(설치) 단위로 남긴다.
///
/// "응답"에는 **"모두 허용"과 "나중에" 둘 다** 포함된다. 이 화면은 앞당겨 묻는
/// 장치일 뿐이고, 거부한 권한은 실제로 필요한 순간에 기존 개별 요청 경로가 다시
/// 묻는다.
abstract interface class PermissionOnboardingStore {
  /// 이 기기에서 권한 안내에 한 번이라도 응답했는지.
  Future<bool> hasAnswered();

  /// 응답했음을 기록한다.
  Future<void> markAnswered();
}
