/** 아동이 그림 활동을 돌아보며 직접 선택할 수 있는 감정 코드를 정의한다. */
public enum DrawingEmotionCode {
  /** 기쁜 감정이다. */
  HAPPY,
  /** 슬픈 감정이다. */
  SAD,
  /** 화난 감정이다. */
  ANGRY,
  /** 무서운 감정이다. */
  SCARED,
  /** 편안하고 차분한 감정이다. */
  CALM,
  /** 현재 감정을 고르기 어려운 경우다. */
  UNKNOWN
}
