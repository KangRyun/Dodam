package com.ssafy.b209.child.domain;

/**
 * 아이가 지금 다니는 곳 (S15P11B209-1010 v2).
 *
 * <p>만 6세(72~83개월)의 발달 맥락을 고를 때 나이와 <strong>함께</strong> 본다. 같은 6세라도
 * 유치원에 다니는 아이와 초등 1학년이 참고할 자료가 다르고, 어린이집에 다니는 아이에게는 어느
 * 학년 자료도 적용하지 않는다.
 *
 * <p><strong>필수가 아니다.</strong> 비어 있으면 학년 자료를 쓰지 않고 이번 활동 관찰만 한다 —
 * 나이만으로 학년을 확정하면 조기 입학·유예를 틀리게 단정한다. 그래서 '모른다'를 값으로 두지
 * 않고 컬럼을 {@code NULL} 로 비운다. 값으로 두면 입력된 것과 구별할 수 없다.
 */
public enum EducationStage {
  /** 어린이집. 학년 자료를 적용하지 않는다. */
  PRESCHOOL,

  /** 유치원. */
  KINDERGARTEN,

  /** 초등학교 1학년. */
  GRADE_1
}
