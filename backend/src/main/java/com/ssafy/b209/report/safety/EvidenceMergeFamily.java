package com.ssafy.b209.report.safety;

/**
 * 여러 근거가 합쳐 최대 1건으로만 세지는 묶음이다(보호자 계약 §4-3, 875 계약 §4-1 조건 3).
 *
 * <p>병합은 <strong>카드 전역</strong>이다 — 한 카드 안에서 같은 묶음의 근거가 몇 건이든, 활동이 다르든 합쳐 1건이다. 활동별로 나누지 않는 이유는 활동을
 * 구분해도 "같은 감정을 두 번 신고한 것"과 "서로 다른 감정 근거 두 건"을 서버가 값 비교로 가릴 수 없기 때문이다. 나눌 수 없으면 합치는 쪽이 보수적이다({@code
 * ai/interpretation_gate.py}의 {@code _merge_families}와 같은 규칙).
 */
enum EvidenceMergeFamily {
  /**
   * 감정 근거 묶음이다.
   *
   * <p>선택 감정은 코드고 말한 감정은 자유 텍스트라 "같은 감정인지"를 서버가 결정적으로 비교할 수 없다. 그래서 계열 전체를 1건으로 본다 — 감정 근거만으로는 공개
   * 조건(2건)을 채울 수 없다.
   */
  EMOTION,
  /** 활동 지표 묶음이다. 지표를 여러 개 나열해 근거 수를 부풀리지 못하게 한다. */
  ACTIVITY_METRIC
}
