package com.ssafy.b209.report.domain;

/**
 * 리포트 관찰 특징을 노출할 수 있는 대상 범위를 나타낸다.
 *
 * <p><b>어휘는 그대로 두고 의미만 재정의했다.</b> 사람 전문가 검토 워크플로가 이 서비스에 없어서 두 값의 원래 뜻("전문가 화면" / "전문가가 검토를 마침")은
 * 가리키는 대상이 없었다. DB에 이미 저장된 값과 AI 계약 문자열을 흔들지 않으려고 값 이름은 유지한다 — 마이그레이션 없이 뜻만 바꾼다.
 */
public enum ReportFeatureVisibility {
  /**
   * 보호자에게 <b>바로 열지 않는</b> 관찰 특징이다.
   *
   * <p>사람 상담 권유·위기 대응 경로에서만 쓰고 보호자 조회 응답에는 담기지 않는다. 신호를 버리는 것이 아니라 열람 경로를 좁히는 것이다.
   */
  EXPERT_ONLY,

  /**
   * 검토를 통과해 보호자에게 노출할 수 있는 관찰 특징이다.
   *
   * <p>검토 주체는 사람 전문가가 아니라 AI 자체 검토다({@code ObservationReviewStatus.AI_REVIEWED}). 그래서 리포트에는 진단이
   * 아니라는 한계 고지가 그대로 함께 나간다(CLAUDE.md 9절).
   */
  REVIEWED_GUARDIAN
}
