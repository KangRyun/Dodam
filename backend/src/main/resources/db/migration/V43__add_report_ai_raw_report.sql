-- S15P11B209-980 리포트 AI 원문 보관
--
-- 리포트 본문은 계약 스키마로 읽은 값만 쓴다. 그 과정에서 스키마에 없는 AI 서술이 사라지는데,
-- 집·나무·사람 활동에서 무엇이 사라지는지 확인하려면 원문이 남아 있어야 한다. 조회 시점에는
-- 다시 만들 수 없어 생성할 때 함께 저장한다.
--
-- NULL 을 허용한다. 이 컬럼이 생기기 전에 만든 리포트와, AI 응답 원문을 받아 두지 못한 리포트는
-- 비어 있는 것이 정상이다.
--
-- LONGTEXT: AI 응답은 주제별 서술이 길어 TEXT(64KB) 를 넘길 수 있다. 원문을 자르면 이 컬럼을
-- 두는 이유가 사라진다.
ALTER TABLE reports
    ADD COLUMN ai_raw_report LONGTEXT NULL COMMENT 'AI 관찰 생성 응답 원문 (S15P11B209-980)';
